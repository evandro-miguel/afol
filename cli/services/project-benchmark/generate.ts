import { existsSync, mkdirSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { atomicWriteText } from "../io/atomic";
import { withSessionLock } from "../io/session-lock";
import type { ProjectBenchmarkMatrix } from "./matrix";
import { buildProjectBenchmarkMatrix } from "./matrix";
import type {
	ProjectBenchmarkAxesFile,
	ProjectBenchmarkProject,
	ProjectBenchmarkScore,
} from "./types";
import type { ProjectBenchmarkValidationResult } from "./validate";

export type ProjectBenchmarkGeneratedFile = {
	path: string;
	kind: "index" | "matrix" | "summary" | "validation";
};

export type ProjectBenchmarkGenerationResult = {
	schema_version: "1.0.0";
	command: "project-benchmark.generate";
	generated_by: "afol pb generate";
	mode: "write" | "check";
	ok: boolean;
	generated_at: string;
	data_dir: string;
	files: ProjectBenchmarkGeneratedFile[];
	changed_files: ProjectBenchmarkGeneratedFile[];
	project_count: number;
};

type ProjectBenchmarkGenerateOptions = {
	check?: boolean;
	now?: Date;
};

type GeneratedIndex = {
	schema_version: "1.0.0";
	generated_by: "afol pb generate";
	generated_at: string;
	project_count: number;
	projects: ProjectBenchmarkScore[];
};

type GeneratedMatrix = Omit<ProjectBenchmarkMatrix, "generated_by"> & {
	generated_by: "afol pb generate";
	generated_at: string;
};

type GeneratedValidationReport = ProjectBenchmarkValidationResult & {
	schema_version: "1.0.0";
	generated_by: "afol pb generate";
	generated_at: string;
};

function writeStableJson(path: string, value: unknown): void {
	writeTextIfChanged(path, `${JSON.stringify(value, null, 2)}\n`);
}

function writeTextIfChanged(path: string, text: string): void {
	if (existsSync(path) && readFileSync(path, "utf8") === text) {
		return;
	}
	atomicWriteText(path, text);
}

function buildSummary(
	generatedAt: string,
	projects: ProjectBenchmarkScore[],
): string {
	const lines = [
		"# Project Benchmark Generated Summary",
		"",
		"> Generated by `afol pb generate`. Do not edit manually.",
		"",
		`Generated at: ${generatedAt}`,
		`Projects: ${projects.length}`,
		"",
		"## Top References",
		"",
		...projects
			.slice(0, 10)
			.map(
				(project) =>
					`- ${project.id}: overall=${project.overall_score} focused=${project.focused_score} category=${project.category} stale=${project.stale}`,
			),
		"",
	];
	return lines.join("\n");
}

function buildGeneratedPayloads(
	generatedAt: string,
	matrix: ProjectBenchmarkMatrix,
	validation: ProjectBenchmarkValidationResult,
): {
	index: GeneratedIndex;
	generatedMatrix: GeneratedMatrix;
	validationReport: GeneratedValidationReport;
	summary: string;
} {
	return {
		index: {
			schema_version: "1.0.0",
			generated_by: "afol pb generate",
			generated_at: generatedAt,
			project_count: matrix.projects.length,
			projects: matrix.projects,
		},
		generatedMatrix: {
			schema_version: matrix.schema_version,
			generated_by: "afol pb generate",
			generated_at: generatedAt,
			projects: matrix.projects,
		},
		validationReport: {
			schema_version: "1.0.0",
			generated_by: "afol pb generate",
			generated_at: generatedAt,
			...validation,
		},
		summary: buildSummary(generatedAt, matrix.projects),
	};
}

function readGeneratedAt(path: string): string | null {
	if (!existsSync(path)) {
		return null;
	}
	try {
		const value = JSON.parse(readFileSync(path, "utf8")) as unknown;
		if (
			typeof value === "object" &&
			value !== null &&
			"generated_at" in value &&
			typeof value.generated_at === "string"
		) {
			return value.generated_at;
		}
	} catch {
		return null;
	}
	return null;
}

function jsonText(value: unknown): string {
	return `${JSON.stringify(value, null, 2)}\n`;
}

type GeneratedFileContent = {
	path: string;
	relativePath: string;
	kind: ProjectBenchmarkGeneratedFile["kind"];
	content: string;
};

function buildGeneratedFiles(
	projectRoot: string,
	dataDir: string,
	payloads: ReturnType<typeof buildGeneratedPayloads>,
): GeneratedFileContent[] {
	return [
		{
			path: join(dataDir, "index.json"),
			relativePath: relative(projectRoot, join(dataDir, "index.json")),
			kind: "index",
			content: jsonText(payloads.index),
		},
		{
			path: join(dataDir, "similarity-matrix.json"),
			relativePath: relative(
				projectRoot,
				join(dataDir, "similarity-matrix.json"),
			),
			kind: "matrix",
			content: jsonText(payloads.generatedMatrix),
		},
		{
			path: join(dataDir, "generated-summary.md"),
			relativePath: relative(
				projectRoot,
				join(dataDir, "generated-summary.md"),
			),
			kind: "summary",
			content: payloads.summary,
		},
		{
			path: join(dataDir, "validation-report.json"),
			relativePath: relative(
				projectRoot,
				join(dataDir, "validation-report.json"),
			),
			kind: "validation",
			content: jsonText(payloads.validationReport),
		},
	];
}

function contentMatches(path: string, content: string): boolean {
	return existsSync(path) && readFileSync(path, "utf8") === content;
}

function publicFile(
	file: Pick<GeneratedFileContent, "relativePath" | "kind">,
): ProjectBenchmarkGeneratedFile {
	return { path: file.relativePath, kind: file.kind };
}

function canReuseGeneratedAt(
	generatedAt: string,
	files: {
		index: string;
		matrix: string;
		summary: string;
		validation: string;
	},
	matrix: ProjectBenchmarkMatrix,
	validation: ProjectBenchmarkValidationResult,
): boolean {
	const payloads = buildGeneratedPayloads(generatedAt, matrix, validation);
	return (
		existsSync(files.index) &&
		existsSync(files.matrix) &&
		existsSync(files.summary) &&
		existsSync(files.validation) &&
		readFileSync(files.index, "utf8") === jsonText(payloads.index) &&
		readFileSync(files.matrix, "utf8") === jsonText(payloads.generatedMatrix) &&
		readFileSync(files.summary, "utf8") === payloads.summary &&
		readFileSync(files.validation, "utf8") ===
			jsonText(payloads.validationReport)
	);
}

export function generateProjectBenchmarkOutputs(
	projectRoot: string,
	dataDir: string,
	projects: ProjectBenchmarkProject[],
	axes: ProjectBenchmarkAxesFile,
	validation: ProjectBenchmarkValidationResult,
	options: ProjectBenchmarkGenerateOptions = {},
): ProjectBenchmarkGenerationResult {
	return withSessionLock(projectRoot, "project-benchmark.generate", () => {
		const now = options.now ?? new Date();
		const check = options.check === true;
		const matrix = buildProjectBenchmarkMatrix(projects, axes, now);
		const paths = {
			index: join(dataDir, "index.json"),
			matrix: join(dataDir, "similarity-matrix.json"),
			summary: join(dataDir, "generated-summary.md"),
			validation: join(dataDir, "validation-report.json"),
		};
		const priorGeneratedAt = readGeneratedAt(paths.index);
		const generatedAt =
			priorGeneratedAt &&
			canReuseGeneratedAt(priorGeneratedAt, paths, matrix, validation)
				? priorGeneratedAt
				: now.toISOString();
		const payloads = buildGeneratedPayloads(generatedAt, matrix, validation);
		const files = buildGeneratedFiles(projectRoot, dataDir, payloads);
		const changedFiles = files.filter(
			(file) => !contentMatches(file.path, file.content),
		);

		if (!check && changedFiles.length > 0) {
			mkdirSync(dataDir, { recursive: true });
			for (const file of changedFiles) {
				if (file.kind === "summary") {
					writeTextIfChanged(file.path, file.content);
					continue;
				}
				writeStableJson(
					file.path,
					file.kind === "index"
						? payloads.index
						: file.kind === "matrix"
							? payloads.generatedMatrix
							: payloads.validationReport,
				);
			}
		}

		return {
			schema_version: "1.0.0",
			command: "project-benchmark.generate",
			generated_by: "afol pb generate",
			mode: check ? "check" : "write",
			ok: check ? changedFiles.length === 0 : true,
			generated_at: generatedAt,
			data_dir: relative(projectRoot, dataDir),
			files: files.map(publicFile),
			changed_files: changedFiles.map(publicFile),
			project_count: matrix.projects.length,
		};
	});
}
