import {
	closeSync,
	existsSync,
	mkdirSync,
	openSync,
	readdirSync,
	readFileSync,
	readSync,
} from "node:fs";
import { join, relative } from "node:path";
import { toPosixPath } from "../../core/file-paths";
import { atomicWriteText } from "../io/atomic";
import { withSessionLock } from "../io/session-lock";
import type { ProjectBenchmarkMatrix } from "./matrix";
import { buildProjectBenchmarkMatrix } from "./matrix";
import type {
	ProjectBenchmarkAxesFile,
	ProjectBenchmarkProject,
	ProjectBenchmarkScore,
	ProjectBenchmarkValidationResult,
} from "./types";

const PROJECT_BENCHMARK_GENERATOR = "afol pb generate" as const;

export type ProjectBenchmarkGeneratedFile = {
	path: string;
	kind: "index" | "matrix" | "summary" | "validation";
};

export type ProjectBenchmarkMisplacedFile = {
	path: string;
	location: "catalog" | "runtime-benchmark-catalog";
};

export type ProjectBenchmarkGenerationResult = {
	schema_version: "1.0.0";
	command: "project-benchmark.generate";
	generated_by: typeof PROJECT_BENCHMARK_GENERATOR;
	mode: "write" | "check";
	ok: boolean;
	generated_at: string;
	data_dir: string;
	files: ProjectBenchmarkGeneratedFile[];
	changed_files: ProjectBenchmarkGeneratedFile[];
	misplaced_files: ProjectBenchmarkMisplacedFile[];
	project_count: number;
};

type ProjectBenchmarkGeneratePaths = {
	dataDir: string;
	catalogDir: string;
	runtimeBenchmarkCatalogDir: string;
};

type ProjectBenchmarkGenerateOptions = {
	check?: boolean;
	now?: Date;
};

type GeneratedIndex = {
	schema_version: "1.0.0";
	generated_by: typeof PROJECT_BENCHMARK_GENERATOR;
	generated_at: string;
	project_count: number;
	projects: ProjectBenchmarkScore[];
};

type GeneratedMatrix = Omit<ProjectBenchmarkMatrix, "generated_by"> & {
	generated_by: typeof PROJECT_BENCHMARK_GENERATOR;
	generated_at: string;
};

type GeneratedValidationReport = ProjectBenchmarkValidationResult & {
	schema_version: "1.0.0";
	generated_by: typeof PROJECT_BENCHMARK_GENERATOR;
	generated_at: string;
};

function writeStableJson(path: string, value: unknown): void {
	writeTextIfChanged(path, `${JSON.stringify(value, null, 2)}\n`);
}

function writeTextIfChanged(path: string, text: string): void {
	if (existsSync(path) && readFileSync(path, "utf8") === text) {
		return;
	}
	atomicWriteText(path, text);
}

function buildSummary(
	generatedAt: string,
	projects: ProjectBenchmarkScore[],
): string {
	const lines = [
		"# Project Benchmark Generated Summary",
		"",
		`> Generated by \`${PROJECT_BENCHMARK_GENERATOR}\`. Do not edit manually.`,
		"",
		`Generated at: ${generatedAt}`,
		`Projects: ${projects.length}`,
		"",
		"## Top References",
		"",
		...projects
			.slice(0, 10)
			.map(
				(project) =>
					`- ${project.id}: overall=${project.overall_score} focused=${project.focused_score} category=${project.category} stale=${project.stale}`,
			),
		"",
	];
	return lines.join("\n");
}

function buildGeneratedPayloads(
	generatedAt: string,
	matrix: ProjectBenchmarkMatrix,
	validation: ProjectBenchmarkValidationResult,
): {
	index: GeneratedIndex;
	generatedMatrix: GeneratedMatrix;
	validationReport: GeneratedValidationReport;
	summary: string;
} {
	return {
		index: {
			schema_version: "1.0.0",
			generated_by: PROJECT_BENCHMARK_GENERATOR,
			generated_at: generatedAt,
			project_count: matrix.projects.length,
			projects: matrix.projects,
		},
		generatedMatrix: {
			schema_version: matrix.schema_version,
			generated_by: PROJECT_BENCHMARK_GENERATOR,
			generated_at: generatedAt,
			projects: matrix.projects,
		},
		validationReport: {
			schema_version: "1.0.0",
			generated_by: PROJECT_BENCHMARK_GENERATOR,
			generated_at: generatedAt,
			...validation,
		},
		summary: buildSummary(generatedAt, matrix.projects),
	};
}

function readGeneratedAt(path: string): string | null {
	if (!existsSync(path)) {
		return null;
	}
	try {
		const value = JSON.parse(readFileSync(path, "utf8")) as unknown;
		if (
			typeof value === "object" &&
			value !== null &&
			"generated_at" in value &&
			typeof value.generated_at === "string"
		) {
			return value.generated_at;
		}
	} catch {
		return null;
	}
	return null;
}

function jsonText(value: unknown): string {
	return `${JSON.stringify(value, null, 2)}\n`;
}

type GeneratedFileContent = {
	path: string;
	relativePath: string;
	kind: ProjectBenchmarkGeneratedFile["kind"];
	content: string;
};

const GENERATED_FILE_NAMES = new Set([
	"index.json",
	"similarity-matrix.json",
	"generated-summary.md",
	"validation-report.json",
]);
const GENERATED_MARKER_READ_LIMIT_BYTES = 64 * 1024;

function buildGeneratedFiles(
	projectRoot: string,
	dataDir: string,
	payloads: ReturnType<typeof buildGeneratedPayloads>,
): GeneratedFileContent[] {
	const indexPath = join(dataDir, "index.json");
	const matrixPath = join(dataDir, "similarity-matrix.json");
	const summaryPath = join(dataDir, "generated-summary.md");
	const validationPath = join(dataDir, "validation-report.json");
	return [
		{
			path: indexPath,
			relativePath: toPosixPath(relative(projectRoot, indexPath)),
			kind: "index",
			content: jsonText(payloads.index),
		},
		{
			path: matrixPath,
			relativePath: toPosixPath(relative(projectRoot, matrixPath)),
			kind: "matrix",
			content: jsonText(payloads.generatedMatrix),
		},
		{
			path: summaryPath,
			relativePath: toPosixPath(relative(projectRoot, summaryPath)),
			kind: "summary",
			content: payloads.summary,
		},
		{
			path: validationPath,
			relativePath: toPosixPath(relative(projectRoot, validationPath)),
			kind: "validation",
			content: jsonText(payloads.validationReport),
		},
	];
}

function contentMatches(path: string, content: string): boolean {
	return existsSync(path) && readFileSync(path, "utf8") === content;
}

function readFilePrefix(path: string): string {
	const file = openSync(path, "r");
	try {
		const buffer = Buffer.alloc(GENERATED_MARKER_READ_LIMIT_BYTES);
		const bytesRead = readSync(file, buffer, 0, buffer.length, 0);
		return buffer.subarray(0, bytesRead).toString("utf8");
	} finally {
		closeSync(file);
	}
}

function fileLooksLikeProjectBenchmarkGeneratedOutput(
	path: string,
	fileName: string,
): boolean {
	if (GENERATED_FILE_NAMES.has(fileName)) {
		return true;
	}
	if (
		!fileName.endsWith(".json") &&
		!fileName.endsWith(".md") &&
		!fileName.endsWith(".txt")
	) {
		return false;
	}
	try {
		const content = readFilePrefix(path);
		if (fileName.endsWith(".json")) {
			try {
				const value = JSON.parse(content) as unknown;
				return (
					typeof value === "object" &&
					value !== null &&
					"generated_by" in value &&
					value.generated_by === PROJECT_BENCHMARK_GENERATOR
				);
			} catch {
				return content.includes(
					`"generated_by": "${PROJECT_BENCHMARK_GENERATOR}"`,
				);
			}
		}
		return content.includes(PROJECT_BENCHMARK_GENERATOR);
	} catch {
		return false;
	}
}

function collectMisplacedOutputs(
	projectRoot: string,
	paths: Pick<
		ProjectBenchmarkGeneratePaths,
		"catalogDir" | "runtimeBenchmarkCatalogDir"
	>,
): ProjectBenchmarkMisplacedFile[] {
	const misplaced = new Map<string, ProjectBenchmarkMisplacedFile>();
	const scan = (
		dir: string,
		location: ProjectBenchmarkMisplacedFile["location"],
	): void => {
		if (!existsSync(dir)) {
			return;
		}
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			const entryPath = join(dir, entry.name);
			if (
				location === "runtime-benchmark-catalog" &&
				entry.isDirectory() &&
				/^project-benchmarks?$/.test(entry.name)
			) {
				const rel = toPosixPath(relative(projectRoot, entryPath) || entryPath);
				misplaced.set(rel, { path: rel, location });
			}
			if (entry.isDirectory()) {
				scan(entryPath, location);
				continue;
			}
			if (
				!fileLooksLikeProjectBenchmarkGeneratedOutput(entryPath, entry.name)
			) {
				continue;
			}
			const rel = toPosixPath(relative(projectRoot, entryPath) || entryPath);
			misplaced.set(rel, { path: rel, location });
		}
	};

	scan(paths.catalogDir, "catalog");
	scan(paths.runtimeBenchmarkCatalogDir, "runtime-benchmark-catalog");
	return [...misplaced.values()].sort((left, right) =>
		left.path.localeCompare(right.path),
	);
}

export function findProjectBenchmarkMisplacedOutputs(
	projectRoot: string,
	paths: Pick<
		ProjectBenchmarkGeneratePaths,
		"catalogDir" | "runtimeBenchmarkCatalogDir"
	>,
): ProjectBenchmarkMisplacedFile[] {
	return collectMisplacedOutputs(projectRoot, paths);
}

function publicFile(
	file: Pick<GeneratedFileContent, "relativePath" | "kind">,
): ProjectBenchmarkGeneratedFile {
	return { path: file.relativePath, kind: file.kind };
}

function canReuseGeneratedAt(
	files: {
		index: string;
		matrix: string;
		summary: string;
		validation: string;
	},
	payloads: ReturnType<typeof buildGeneratedPayloads>,
): boolean {
	return (
		existsSync(files.index) &&
		existsSync(files.matrix) &&
		existsSync(files.summary) &&
		existsSync(files.validation) &&
		readFileSync(files.index, "utf8") === jsonText(payloads.index) &&
		readFileSync(files.matrix, "utf8") === jsonText(payloads.generatedMatrix) &&
		readFileSync(files.summary, "utf8") === payloads.summary &&
		readFileSync(files.validation, "utf8") ===
			jsonText(payloads.validationReport)
	);
}

export function generateProjectBenchmarkOutputs(
	projectRoot: string,
	generatePaths: ProjectBenchmarkGeneratePaths,
	projects: ProjectBenchmarkProject[],
	axes: ProjectBenchmarkAxesFile,
	validation: ProjectBenchmarkValidationResult,
	options: ProjectBenchmarkGenerateOptions = {},
): ProjectBenchmarkGenerationResult {
	return withSessionLock(projectRoot, "project-benchmark.generate", () => {
		const now = options.now ?? new Date();
		const check = options.check === true;
		const matrix = buildProjectBenchmarkMatrix(projects, axes, now);
		const misplacedFiles = collectMisplacedOutputs(projectRoot, generatePaths);
		const filePaths = {
			index: join(generatePaths.dataDir, "index.json"),
			matrix: join(generatePaths.dataDir, "similarity-matrix.json"),
			summary: join(generatePaths.dataDir, "generated-summary.md"),
			validation: join(generatePaths.dataDir, "validation-report.json"),
		};
		const priorGeneratedAt = readGeneratedAt(filePaths.index);
		const priorPayloads = priorGeneratedAt
			? buildGeneratedPayloads(priorGeneratedAt, matrix, validation)
			: null;
		const generatedAt =
			priorGeneratedAt &&
			priorPayloads &&
			canReuseGeneratedAt(filePaths, priorPayloads)
				? priorGeneratedAt
				: now.toISOString();
		const payloads =
			generatedAt === priorGeneratedAt && priorPayloads
				? priorPayloads
				: buildGeneratedPayloads(generatedAt, matrix, validation);
		const files = buildGeneratedFiles(
			projectRoot,
			generatePaths.dataDir,
			payloads,
		);
		const changedFiles = files.filter(
			(file) => !contentMatches(file.path, file.content),
		);

		if (!check && misplacedFiles.length === 0 && changedFiles.length > 0) {
			mkdirSync(generatePaths.dataDir, { recursive: true });
			for (const file of changedFiles) {
				if (file.kind === "summary") {
					writeTextIfChanged(file.path, file.content);
					continue;
				}
				writeStableJson(
					file.path,
					file.kind === "index"
						? payloads.index
						: file.kind === "matrix"
							? payloads.generatedMatrix
							: payloads.validationReport,
				);
			}
		}

		return {
			schema_version: "1.0.0",
			command: "project-benchmark.generate",
			generated_by: PROJECT_BENCHMARK_GENERATOR,
			mode: check ? "check" : "write",
			ok:
				misplacedFiles.length === 0 &&
				(check ? changedFiles.length === 0 : true),
			generated_at: generatedAt,
			data_dir: toPosixPath(relative(projectRoot, generatePaths.dataDir)),
			files: files.map(publicFile),
			changed_files: changedFiles.map(publicFile),
			misplaced_files: misplacedFiles,
			project_count: matrix.projects.length,
		};
	});
}
